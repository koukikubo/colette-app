export function guidesForRole(role?: string): FeatureGuide[] {
  const authenticated = ["owner", "operator", "viewer"].includes(role ?? "");
  return featureGuides
    .filter((guide) => authenticated || guide.public)
    .map((guide) => ({
      ...guide,
      topics: guide.topics.filter(
        (topic) =>
          (!topic.ownerOnly || role === "owner") &&
          (!topic.resource || canWrite(role, topic.resource)),
      ),
    }));
}
export function guideForPath(pathname: string) {
  return featureGuides.find((guide) =>
    guide.paths.some((path) => path.test(pathname)),
  );
}
